/**
 * Dialog for configuring global default AI smart replies and testing connection.
 */
@Composable
fun AiSmartReplyConfigDialog(
    defaultReplyCount: Int,
    isTesting: Boolean,
    testResult: String?,
    onTestConnection: () -> Unit,
    onSaveReplyCount: (Int) -> Unit,
    onDismiss: () -> Unit
) {
    var replyCountSelection by remember(defaultReplyCount) { mutableIntStateOf(defaultReplyCount) }

    AlertDialog(
        onDismissRequest = onDismiss,
        shape = Dimens.DialogShape,
        title = {
            Text(
                text = "AI Smart Reply Configuration",
                style = MaterialTheme.typography.titleMedium,
                fontWeight = FontWeight.Bold
            )
        },
        text = {
            Column(
                verticalArrangement = Arrangement.spacedBy(Dimens.SpacingMedium),
                modifier = Modifier.fillMaxWidth()
            ) {
                Text(
                    text = "Configure the global default smart replies generated by the AI backend service.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )

                // Default Number of Replies
                Column(verticalArrangement = Arrangement.spacedBy(Dimens.SpacingSmall)) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Text(
                            text = "Default Number of Replies",
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = FontWeight.SemiBold
                        )
                        Text(
                            text = "$replyCountSelection ${if (replyCountSelection == 1) "reply" else "replies"}",
                            style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.primary,
                            fontWeight = FontWeight.Bold
                        )
                    }

                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(6.dp)
                    ) {
                        (1..5).forEach { count ->
                            FilterChip(
                                selected = replyCountSelection == count,
                                onClick = { replyCountSelection = count },
                                label = {
                                    Text(
                                        text = "$count",
                                        fontWeight = if (replyCountSelection == count) FontWeight.Bold else FontWeight.Normal,
                                        modifier = Modifier.fillMaxWidth(),
                                        textAlign = TextAlign.Center
                                    )
                                },
                                modifier = Modifier.weight(1f)
                            )
                        }
                    }
                }

                OutlinedButton(
                    onClick = onTestConnection,
                    enabled = !isTesting,
                    shape = Dimens.SquircleShape,
                    modifier = Modifier.fillMaxWidth()
                ) {
                    if (isTesting) {
                        CircularProgressIndicator(modifier = Modifier.size(16.dp), strokeWidth = 2.dp)
                        Spacer(modifier = Modifier.width(Dimens.SpacingSmall))
                        Text("Testing AI Service...")
                    } else {
                        Text("Test AI Connection", fontWeight = FontWeight.SemiBold)
                    }
                }

                if (testResult != null) {
                    Surface(
                        shape = Dimens.CardShape,
                        color = if (testResult.startsWith("Error")) {
                            MaterialTheme.colorScheme.errorContainer
                        } else {
                            MaterialTheme.colorScheme.primaryContainer
                        },
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Text(
                            text = testResult,
                            style = MaterialTheme.typography.bodySmall,
                            fontWeight = FontWeight.Medium,
                            color = if (testResult.startsWith("Error")) {
                                MaterialTheme.colorScheme.onErrorContainer
                            } else {
                                MaterialTheme.colorScheme.onPrimaryContainer
                            },
                            modifier = Modifier.padding(Dimens.SpacingSmall)
                        )
                    }
                }
            }
        },
        confirmButton = {
            Button(
                onClick = { onSaveReplyCount(replyCountSelection) },
                shape = Dimens.SquircleShape
            ) {
                Text("Save", fontWeight = FontWeight.SemiBold)
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text("Cancel")
            }
        }
    )
}

/**
 * Dialog for managing connected email accounts (edit sender display name, disconnect account).
 */
@Composable
fun ManageEmailAccountDialog(
    account: EmailAccountEntity,
    onSaveDisplayName: (String) -> Unit,
    onDisconnect: () -> Unit,
    onDismiss: () -> Unit
) {
    var senderNameInput by remember(account) { mutableStateOf(account.displayName.orEmpty()) }

    AlertDialog(
        onDismissRequest = onDismiss,
        shape = Dimens.DialogShape,
        title = {
            Text(
                text = "Manage Account",
                style = MaterialTheme.typography.titleMedium,
                fontWeight = FontWeight.Bold
            )
        },
        text = {
            Column(
                verticalArrangement = Arrangement.spacedBy(Dimens.SpacingMedium),
                modifier = Modifier.fillMaxWidth()
            ) {
                Text(
                    text = account.emailAddress,
                    style = MaterialTheme.typography.bodyMedium,
                    fontWeight = FontWeight.SemiBold,
                    color = MaterialTheme.colorScheme.onSurface
                )

                OutlinedTextField(
                    value = senderNameInput,
                    onValueChange = { senderNameInput = it },
                    label = { Text("Sender Name") },
                    placeholder = { Text("Name shown on replies") },
                    singleLine = true,
                    shape = Dimens.InputShape,
                    modifier = Modifier.fillMaxWidth()
                )

                Spacer(modifier = Modifier.height(Dimens.SpacingMicro))

                TextButton(
                    onClick = onDisconnect,
                    colors = ButtonDefaults.textButtonColors(contentColor = MaterialTheme.colorScheme.error),
                    modifier = Modifier.align(Alignment.Start)
                ) {
                    Icon(
                        imageVector = Icons.Default.DeleteOutline,
                        contentDescription = null,
                        modifier = Modifier.size(18.dp)
                    )
                    Spacer(modifier = Modifier.width(Dimens.SpacingSmall))
                    Text("Disconnect Account", fontWeight = FontWeight.SemiBold)
                }
            }
        },
        confirmButton = {
            Button(
                onClick = { onSaveDisplayName(senderNameInput.trim()) },
                shape = Dimens.SquircleShape
            ) {
                Text("Save")
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text("Cancel")
            }
        }
    )
}

/**
 * Confirmation dialog before signing out and clearing local cache.
 */
@Composable
fun SignOutConfirmDialog(
    onConfirm: () -> Unit,
    onDismiss: () -> Unit
) {
    AlertDialog(
        onDismissRequest = onDismiss,
        shape = Dimens.DialogShape,
        title = { Text("Sign Out", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold) },
        text = {
            Text(
                "Are you sure you want to sign out? All your local data (messages, contacts, accounts, and AI cache) will be removed from this device. App permissions will remain granted.",
                style = MaterialTheme.typography.bodyMedium
            )
        },
        confirmButton = {
            Button(
                onClick = onConfirm,
                colors = ButtonDefaults.buttonColors(containerColor = MaterialTheme.colorScheme.error),
                shape = Dimens.SquircleShape
            ) {
                Text("Sign Out")
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text("Cancel")
            }
        }
    )
}
